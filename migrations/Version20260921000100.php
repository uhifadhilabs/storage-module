/**
 * ONE WRITABLE TARGET, THE PLACE EACH FILE IS IN, AND THE SWITCH BETWEEN THEM.
 *
 * The first tables this bundle has ever owned. It owned none for most of its
 * life and said so — the photo records stay in the modules that own them —
 * and what changed is that "which place do we write to" is a decision
 * somebody makes at a moment rather than a line in a config file.
 *
