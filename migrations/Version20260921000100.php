 * would mean walking every module's records from a migration, which is a
 * migration reaching into schemas it does not own. {@see StorageLocator}
 * reads a file with no row as being in the CURRENT place, which is exactly
 * right for an installation that has only ever had one — and an installation
 * only ever has more than one after a switch, from which point every file is
 * recorded as it is written. The `files:locations:backfill` path, if one is
 * ever wanted for a huge existing installation, is a command and not this.
 */
